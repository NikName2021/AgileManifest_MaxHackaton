const BY_CODE = new Map(REGIONS.map((r) => [r.code, r]));

function tokenize(text: string): string[] {
  return text
    .toLowerCase()
    .replace(/ё/g, 'е')
    .split(/[^a-zа-я0-9]+/)
    .filter(Boolean);
}

// Совпадение основы из нескольких слов: каждое слово основы — начало соседних слов текста.
function matchesAt(tokens: string[], i: number, stemWords: string[]): boolean {
  return stemWords.every((w, k) => {
    const token = tokens[i + k];
    if (!token) return false;
    // Короткие однословные основы («уф», «чит», «мск») — только с окончанием до 2 букв.
    const short = stemWords.length === 1 && w.length <= 3;
    return short ? token.startsWith(w) && token.length <= w.length + 2 : token.startsWith(w);
  });
}

export function regionByCode(code: string | null | undefined): Region | undefined {
  return code ? BY_CODE.get(code) : undefined;
}

// Код субъекта по свободному тексту («под Краснодаром», «Кубань», «23», «Краснодарский край»).
// Выбирается самая длинная совпавшая основа, чтобы «Нижний Новгород» не стал Новгородской областью.
export function normalizeRegion(text: string | null | undefined): string | null {
  if (!text) return null;
  const trimmed = text.trim();
  if (/^\d{2}$/.test(trimmed)) return BY_CODE.has(trimmed) ? trimmed : null;
  const thirteen = /^(\d{2})0{11}$/.exec(trimmed);
  if (thirteen) return BY_CODE.has(thirteen[1]) ? thirteen[1] : null;

  const tokens = tokenize(trimmed);
  let best: { code: string; length: number } | null = null;
  for (const region of REGIONS) {
    for (const stem of region.stems) {
      const stemWords = stem.split(' ');
      if (best && stem.length <= best.length) continue;
      for (let i = 0; i < tokens.length; i++) {
        if (matchesAt(tokens, i, stemWords)) {
          best = { code: region.code, length: stem.length };
          break;
        }
      }
    }
  }
  return best?.code ?? null;
}

// Формат кода региона в API «Работы России»: 13 цифр, например 2300000000000.
export function trudvsemRegionCode(code: string): string {
  return `${code}00000000000`;
}
