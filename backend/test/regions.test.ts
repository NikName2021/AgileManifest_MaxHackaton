import { describe, expect, it } from 'vitest';
import { normalizeRegion, REGIONS, trudvsemRegionCode } from '../src/regions/dictionary.js';

describe('normalizeRegion', () => {
  const cases: [string, string | null][] = [
    ['Краснодар', '23'],
    ['под Краснодаром', '23'],
    ['Краснодарский край, Динской район', '23'],
    ['Кубань', '23'],
    ['Сочи', '23'],
    ['23', '23'],
    ['2300000000000', '23'],
    ['Нижний Новгород', '52'],
    ['Великий Новгород', '53'],
    ['Новгородская обл.', '53'],
    ['Сахалин', '65'],
    ['Якутия', '14'],
    ['Москва', '77'],
    ['Подмосковье', '50'],
    ['Московская область', '50'],
    ['Санкт-Петербург', '78'],
    ['Питер', '78'],
    ['СПб', '78'],
    ['Ленобласть', '47'],
    ['Ростов-на-Дону', '61'],
    ['Казань', '16'],
    ['Уфа', '02'],
    ['Чита', '75'],
    ['Крым, Ялта', '91'],
    ['Севастополь', '92'],
    ['Ставрополье', '26'],
    ['Пятигорск', '26'],
    ['Алтайский край', '22'],
    ['Республика Алтай', '04'],
    ['Екатеринбург', '66'],
    ['Тула', '71'],
    ['Томск', '70'],
    ['Омск', '55'],
    ['Орёл', '57'],
    ['деревня Простоквашино', null],
    ['Алтай', null],
    ['', null],
    ['99', null],
  ];
  it.each(cases)('%s -> %s', (text, code) => {
    expect(normalizeRegion(text)).toBe(code);
  });

  it('коды уникальны, у каждого субъекта есть основы', () => {
    expect(new Set(REGIONS.map((r) => r.code)).size).toBe(REGIONS.length);
    expect(REGIONS.length).toBe(85);
    for (const r of REGIONS) expect(r.stems.length).toBeGreaterThan(0);
  });

  it('формат кода «Работы России»', () => {
    expect(trudvsemRegionCode('23')).toBe('2300000000000');
  });
});
