// Общий helper экранирования MAX markdown (format: 'markdown' стоит по умолчанию почти на всех
// исходящих сообщениях, см. max/client.ts sendMessage). Раньше экранировался только текст карточки
// вакансии (vacancies/publish.ts) — везде, где в сообщение подставляется пользовательский текст
// (название вакансии, имя кандидата, контакт и т.п.), нужно применять эту же функцию, иначе
// спецсимволы могут сломать разметку или (в теории) исказить смысл сообщения.
export function escapeMarkdown(text: string): string {
  return text.replace(/([\\`*_\[\]()~>#+\-=|{}.!])/g, '\\$1');
}
